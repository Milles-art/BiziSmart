test('cashier uses Laravel login, sees approved permissions, and cannot restore a stored fake session', async ({ page }, info) => {
  const label = info.project.name.startsWith('mobile') ? 'mobile' : 'desktop';
  await page.addInitScript((label) => {
    localStorage.setItem('bizismart.device.v1', `e2e-${label}-approved`);
    localStorage.setItem('bizismart-demo-v2', JSON.stringify({ version: 2, business: { currentUser: { role: 'Owner' } } }));
  }, label);
  await page.goto('http://e2e-shop.localhost:15173/');
  await expect(page.getByRole('heading', { name: 'Sign In' })).toBeVisible();
  await page.getByLabel('Phone Number').fill(label === 'mobile' ? '0711111102' : '0711111101');
  await page.getByLabel('4–6 digit PIN').fill('2468');
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Browser Test Supermarket' })).toBeVisible();
  const menu = page.getByRole('button', { name: 'Open navigation' });
  if (await menu.isVisible()) await menu.click();
  await expect(page.getByRole('button', { name: 'Staff', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Settings', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Reports', exact: true })).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Browser Test Supermarket' })).toBeVisible();
  const restoredMenu = page.getByRole('button', { name: 'Open navigation' });
  if (await restoredMenu.isVisible()) await restoredMenu.click();
  await expect(page.getByRole('button', { name: 'Staff', exact: true })).toHaveCount(0);
  expect(await page.evaluate(() => Object.keys(JSON.parse(sessionStorage.getItem('bizismart.session.v1'))).sort())).toEqual(['deviceUid', 'expiresAt', 'lastActiveAt', 'token']);
  await page.getByRole('button', { name: 'Logout', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sign In' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Sign In' })).toBeVisible();
  expect(await page.evaluate(() => sessionStorage.getItem('bizismart.session.v1'))).toBeNull();
  await page.screenshot({ path: `tmp/live-login-${info.project.name}.png`, fullPage: true });
});
